import re

text = ("Дата: 23.10.2026 и 05.11.26; время: 14:58 и 14.58; "
        "числа: -42 +17 12.5 -.75 10; "
        "слова: abc12def аааБББввв ABC тест5 мир7 Москва Apple арбуз Orange.")

#Даты в формате дд.мм.гг или дд.мм.гггг
print("1.", re.findall(r'\b(?:0[1-9]|[12]\d|3[01])\.(?:0[1-9]|1[0-2])\.(?:\d{4}|\d{2})\b', text))

#Время в формате чч.мм или чч:мм
print("2.", re.findall(r'(?<![\w.])(?:[01]\d|2[0-3])[:.][0-5]\d(?![\w.])', text))

#Целые числа со знаком и без
print("3.", re.findall(r'(?<![\w.])[+-]?\d+(?![\w.])', text))

#Вещественные числа со знаком и без
print("4.", re.findall(r'(?<![\w.])[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?![\w.])', text))

#Натуральные числа, в том числе внутри слов
print("5.", re.findall(r'(?<![\d.\-])[1-9]\d*(?![\d.])', text))

#Последовательности заглавных букв
print("6.", re.findall(r'[А-ЯЁA-Z]+', text))

#Слова с русской буквой, после которой есть цифра
print("7.", re.findall(r'\b\w*[А-Яа-яЁё]\w*\d\w*\b', text))

#Слова, начинающиеся с заглавной буквы
print("8.", re.findall(r'\b[А-ЯЁA-Z]\w*\b', text))

#Слова, начинающиеся с гласной буквы
print("9.", re.findall(r'\b[АаЕеЁёИиОоУуЫыЭэЮюЯяAaEeIiOoUu]\w*\b', text))